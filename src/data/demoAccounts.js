export const validateDemoLogin = (email, password) => {
  const normalizedEmail = normalizeEmail(email)
  return demoAccounts.find(account => normalizeEmail(account.email) === normalizedEmail && String(account.password) === String(password)) || null
}

export const getDemoAccountByUid = uid => demoAccounts.find(account => account.uid === uid) || null

